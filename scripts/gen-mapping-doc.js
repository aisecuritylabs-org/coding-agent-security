#!/usr/bin/env node
// Generates claude-code/audit/FRAMEWORK-MAPPING.md from mappings.json.
// Usage: node scripts/gen-mapping-doc.js   (run from the repository root)
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'claude-code', 'audit');
const m = JSON.parse(fs.readFileSync(path.join(dir, 'mappings.json'), 'utf8'));
const titles = {}; // check titles come from the check reference in README.md
const readme = fs.readFileSync(path.join(dir, 'README.md'), 'utf8');
for (const [, id, what] of readme.matchAll(/^\| ([A-Z]\d{2}) \| (.+?) \|/gm)) titles[id] = what;

const fw = m.frameworks;
const cell = (ids, k) => ids.length ? ids.map((id) => k === 'nist_ai_rmf' ? id : `${id} ${fw[k].items[id]}`).join('<br>') : '—';

let out = `<!-- Generated by scripts/gen-mapping-doc.js from mappings.json — do not edit by hand. -->

# Framework mapping

Why each audit check matters, where the information comes from, and how it maps to four AI security frameworks. The same data is embedded in every audit report. For the real attacks behind the newer checks, see [THREATS.md](../THREATS.md).

| Framework | Version |
| --- | --- |
${Object.values(fw).map((f) => `| [${f.name}](${f.url}) | ${f.version} |`).join('\n')}

${m.about}

## Checks

| Check | Why it matters | OWASP LLM | OWASP Agentic | MITRE ATLAS | NIST AI RMF | Sources |
| --- | --- | --- | --- | --- | --- | --- |
`;
for (const [id, c] of Object.entries(m.checks)) {
  const src = (c.sources || []).map((s) => `[${s.title}](${s.url})`).join('<br>') || '—';
  out += `| **${id}** ${titles[id] ? '— ' + titles[id] : ''} | ${c.why} | ${cell(c.owasp_llm, 'owasp_llm')} | ${cell(c.owasp_agentic, 'owasp_agentic')} | ${cell(c.mitre_atlas, 'mitre_atlas')} | ${cell(c.nist_ai_rmf, 'nist_ai_rmf')} | ${src} |\n`;
}

out += `\n## By framework\n`;
for (const [k, f] of Object.entries(fw)) {
  out += `\n### ${f.name} (${f.version})\n\n| ID | ${k === 'nist_ai_rmf' ? 'Subcategory' : 'Title'} | Checks |\n| --- | --- | --- |\n`;
  for (const [id, title] of Object.entries(f.items)) {
    const checks = Object.entries(m.checks).filter(([, c]) => c[k].includes(id)).map(([cid]) => cid);
    out += `| ${id} | ${title} | ${checks.join(', ')} |\n`;
  }
}
fs.writeFileSync(path.join(dir, 'FRAMEWORK-MAPPING.md'), out);
console.log('Wrote claude-code/audit/FRAMEWORK-MAPPING.md');
